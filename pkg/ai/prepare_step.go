package ai

import (
	"context"

	"github.com/aarock1234/ai/pkg/model"
)

// PrepareStepFunc adjusts the settings of one step before its model call. A
// nil result keeps the outer settings.
type PrepareStepFunc func(ctx context.Context, options PrepareStepOptions) (*PrepareStepResult, error)

// PrepareStepOptions describe the step about to run.
type PrepareStepOptions struct {
	// Model is the model of the generation.
	Model model.LanguageModel

	// Steps are the completed steps.
	Steps []StepResult

	// StepNumber is the zero-based index of the step.
	StepNumber int

	// System is the system prompt for the step.
	System string

	// InitialSystem is the system prompt of the generation.
	InitialSystem string

	// Messages are the messages for the step.
	Messages []model.Message

	// InitialMessages are the messages of the generation's prompt.
	InitialMessages []model.Message

	// ResponseMessages are the messages generated by the completed steps.
	ResponseMessages []model.Message
}

// PrepareStepResult overrides settings for one step. Nil and empty fields
// keep the outer settings. Model, tool and call settings apply to this step
// only; System and Messages carry forward to later steps.
type PrepareStepResult struct {
	Model model.LanguageModel

	ToolChoice *model.ToolChoice

	// ActiveTools restricts the tools for the step. An empty, non-nil slice
	// disables every tool.
	ActiveTools []string

	ToolOrder []string

	// System replaces the system prompt.
	System *string

	// Messages replaces the messages sent to the model.
	Messages []model.Message

	// ProviderOptions are merged over the generation's provider options.
	ProviderOptions model.ProviderOptions

	MaxOutputTokens  *int
	Temperature      *float64
	TopP             *float64
	TopK             *int
	PresencePenalty  *float64
	FrequencyPenalty *float64
	StopSequences    []string
	Seed             *int
	Reasoning        model.ReasoningEffort
}

// stepCallSettings applies the call setting overrides of a step to the
// generation's settings. Defined zero values, such as a temperature of 0,
// override as well.
func stepCallSettings(settings CallSettings, overrides PrepareStepResult) CallSettings {
	stepSettings := settings

	if overrides.MaxOutputTokens != nil {
		stepSettings.MaxOutputTokens = overrides.MaxOutputTokens
	}

	if overrides.Temperature != nil {
		stepSettings.Temperature = overrides.Temperature
	}

	if overrides.TopP != nil {
		stepSettings.TopP = overrides.TopP
	}

	if overrides.TopK != nil {
		stepSettings.TopK = overrides.TopK
	}

	if overrides.PresencePenalty != nil {
		stepSettings.PresencePenalty = overrides.PresencePenalty
	}

	if overrides.FrequencyPenalty != nil {
		stepSettings.FrequencyPenalty = overrides.FrequencyPenalty
	}

	if overrides.StopSequences != nil {
		stepSettings.StopSequences = overrides.StopSequences
	}

	if overrides.Seed != nil {
		stepSettings.Seed = overrides.Seed
	}

	if overrides.Reasoning != "" {
		stepSettings.Reasoning = overrides.Reasoning
	}

	return stepSettings
}
